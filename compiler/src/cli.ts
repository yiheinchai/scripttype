function cmdBuild(args: Args, { emit }: { emit: boolean }): number {
  const files = collect(args.positionals.length ? args.positionals : ['.'])
  if (!files.length) throw new UserError('no ScriptType files found (looking for *.st.ts)')

  const outDir = typeof args.flags.out === 'string' ? args.flags.out : undefined
  const toStdout = !!args.flags.stdout
  const force = !!args.flags.force
  const json = !!args.flags.json
  const started = Date.now()
  jsonDiagnostics.length = 0

  let errors = 0
  let warnings = 0
  let written = 0

  for (const file of files) {
    const r = processFile(file, { checkSource: !args.flags['no-check-source'] })
    const counts = report(r, json)
    errors += counts.errors
    warnings += counts.warnings
    if (!r.code || counts.errors) continue

    const body = BANNER(path.basename(file)) + '\n\n' + r.code
    if (toStdout) {
      process.stdout.write(body)
      continue
    }
    if (!emit || json) continue

    const dest = outputPath(file, outDir)
    // Never clobber a hand-written file that happens to sit at the output path.
    if (fs.existsSync(dest) && !force) {
      const existing = fs.readFileSync(dest, 'utf8')
      if (!existing.startsWith('// Generated by ScriptType')) {
        process.stderr.write(
          `${red('error')}: refusing to overwrite ${display(dest)} — it was not generated by ScriptType.\n` +
            `${green('help')}: pass --force, or --out <dir> to write elsewhere.\n\n`,
        )
        errors++
        continue
      }
      if (existing === body) continue // unchanged; leave mtime alone for watchers
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, body)
    written++
    if (!args.flags.quiet) {
      process.stdout.write(`${green('✓')} ${display(file)} ${dim('→')} ${display(dest)}\n`)
    }
  }

  const ms = Date.now() - started
  if (json) {
    process.stdout.write(
      JSON.stringify(
        { files: files.length, errors, warnings, durationMs: ms, diagnostics: jsonDiagnostics },
        null,
        2,
      ) + '\n',
    )
    return errors ? 1 : 0
  }

  const parts = [dim(`${files.length} file${files.length === 1 ? '' : 's'}`)]
  if (emit && !toStdout) parts.push(dim(`${written} written`))
  if (warnings) parts.push(yellow(`${warnings} warning${warnings === 1 ? '' : 's'}`))
  parts.push(errors ? red(`${errors} error${errors === 1 ? '' : 's'}`) : green('0 errors'))
  if (!toStdout && !args.flags.quiet) {
    process.stdout.write(`\n${parts.join(dim(' · '))} ${dim(`(${ms}ms)`)}\n`)
  }
  return errors ? 1 : 0
}

/**
 * Turn existing TypeScript type aliases into ScriptType.
 *
 * This is the migration path. Without it, adopting ScriptType in a codebase that already
 * has type-level code means rewriting all of it by hand, which nobody is going to do —
 * and the decompiler that does the work already round-trips most of a 26-library corpus.
 *
 * Every converted alias is verified by recompiling it and comparing the result to the
 * original text, so the output says which conversions are trustworthy rather than
 * leaving the user to find out.
 */
function cmdConvert(args: Args): number {
  const inputs = args.positionals.length ? args.positionals : ['.']
  const files: string[] = []
  // A `.d.ts` is usually build output, so a directory walk skips it — but plenty of
  // libraries ship their type-level code that way, so the skip is reported rather than
  // silent, and `--declarations` opts back in.
  const wantDeclarations = !!args.flags.declarations
  let skippedDeclarations = 0
  for (const i of inputs) {
    const p = path.resolve(i)
    if (!fs.existsSync(p)) throw new UserError(`no such file or directory: ${display(p)}`)
    if (fs.statSync(p).isDirectory()) {
      const walk = (d: string) => {
        for (const e of fs.readdirSync(d, { withFileTypes: true })) {
          if (e.name === 'node_modules' || e.name.startsWith('.')) continue
          const c = path.join(d, e.name)
          if (e.isDirectory()) {
            walk(c)
          } else if (/\.ts$/.test(c) && !/\.st\.ts$/.test(c)) {
            if (!/\.d\.ts$/.test(c)) files.push(c)
            else if (wantDeclarations) files.push(c)
            else skippedDeclarations++
          }
        }
      }
      walk(p)
    } else files.push(p)
  }
  if (!files.length) {
    throw new UserError(
      skippedDeclarations
        ? `no TypeScript files found — skipped ${skippedDeclarations} .d.ts file(s), which are ` +
          `usually build output. Pass --declarations to convert them anyway.`
        : 'no TypeScript files found',
    )
  }
  if (skippedDeclarations && !args.flags.quiet) {
    process.stdout.write(
      dim(`skipping ${skippedDeclarations} .d.ts file(s); pass --declarations to include them\n`),
    )
  }

  const outDir = typeof args.flags.out === 'string' ? args.flags.out : undefined
  let converted = 0
  let needsWork = 0
  let skipped = 0

  // Two passes. The second needs to know which files actually produced a `.st.ts`,
  // because a specifier is only redirected to `./x.st.js` if that file exists — a module
  // with nothing generic in it is not converted, and pointing at its ScriptType would
  // dangle.
  const decompiled = new Map<string, ReturnType<typeof decompileFile>>()
  const passthrough = new Map<string, string[]>()
  /** Names each converted module exports in type space, keyed by extensionless path. */
  const typeExports = new Map<string, Set<string>>()
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8')
    try {
      const entries = decompileFile(file, text)
      // Non-generic aliases are not ScriptType's business, but dropping them would make
      // the converted module export less than the original and break every importer.
      // The compiler passes a plain `type X = …` straight through, so carry them over.
      const plain = plainAliases(file, text)
      if (entries.length) {
        decompiled.set(file, entries)
        passthrough.set(file, plain)
        typeExports.set(
          file.replace(/(\.d)?\.ts$/, ''),
          new Set(plain.flatMap((p) => p.match(/type (\w+) =/g)?.map((m) => m.slice(5, -2)) ?? [])),
        )
      }
    } catch (e) {
      process.stderr.write(`${red('error')}: ${display(file)}: ${(e as Error).message}\n`)
    }
  }
  const produced = new Set(decompiled.keys())
  skipped = files.length - produced.size

  for (const [file, entries] of decompiled) {
    const text = fs.readFileSync(file, 'utf8')

    const blocks: string[] = []
    for (const p of passthrough.get(file) ?? []) blocks.push(p)
    for (const { name, result } of entries) {
      // `raw()` means the decompiler could not express the construct; the user has to
      // finish it by hand, so say so at the point where the work is.
      const notes = result.gaps.length
        ? `// TODO(scripttype): ${result.gaps.length} construct(s) kept as raw TypeScript — ` +
          `${[...new Set(result.gaps)].join(', ')}\n`
        : ''
      if (result.gaps.length) needsWork++
      else converted++
      blocks.push(`// ${name}\n${notes}${result.source.trim()}`)
    }

    const header =
      `// Converted from ${path.basename(file)} by \`scripttype convert\`.\n` +
      `// Review before committing: compile with \`scripttype build\` and check the output\n` +
      `// against the original.\n`
    const code = blocks.join('\n\n') + '\n'
    // Carry the original file's imports over. Without them a converted file that
    // references a type from a sibling module has an unresolved name, which is most
    // real files — and they must become *value* imports, because ScriptType calls a
    // type function rather than naming it.
    const alreadyTyped = new Set<string>()
    const imports = carriedImports(text, code, file, produced, typeExports, alreadyTyped)
    // Derived from the finished code *including* its imports, not per block: a name is
    // only given a type-space alias if something in the file actually uses it in type
    // position, and whether it is imported or local makes no difference to that.
    const aliases = declareLocalTypeAliases(imports + code, alreadyTyped)
    const body =
      header + '\n' + (imports ? imports + '\n' : '') + (aliases ? aliases + '\n' : '') + code

    // `words.d.ts` becomes `words.st.ts`, not `words.d.st.ts`: the result is ScriptType
    // source, not a declaration file, and the name has to agree with the `./words.st.js`
    // specifier that sibling conversions emit for it.
    const dest = path.join(
      outDir ?? path.dirname(file),
      path.basename(file).replace(/(\.d)?\.ts$/, '.st.ts'),
    )
    if (args.flags.stdout) {
      process.stdout.write(body)
      continue
    }
    if (fs.existsSync(dest) && !args.flags.force) {
      process.stderr.write(
        `${red('error')}: ${display(dest)} already exists.\n${green('help')}: pass --force to replace it.\n`,
      )
      continue
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, body)
    process.stdout.write(
      `${green('✓')} ${display(file)} ${dim('→')} ${display(dest)} ${dim(`(${entries.length} aliases)`)}\n`,
    )
  }

  if (!args.flags.stdout) {
    const parts = [dim(`${converted} converted`)]
    if (needsWork) parts.push(yellow(`${needsWork} need review`))
    if (skipped) parts.push(dim(`${skipped} file(s) had no generic type aliases`))
    process.stdout.write(`\n${parts.join(dim(' · '))}\n`)
    if (needsWork) {
      process.stdout.write(
        dim('Search the output for TODO(scripttype) to find what needs finishing by hand.\n'),
      )
    }
  }
  return 0
}

/**
 * The original file's imports, rewritten for ScriptType source.
 *
 * Two changes. They become *value* imports, because a ScriptType type function is
 * called rather than named. And a specifier pointing at another file in the same
 * conversion is redirected to that file's ScriptType (`./words.js` -> `./words.st.js`),
 * since after conversion that is where the callable form lives.
 *
 * Only names the converted code actually mentions are kept; a file typically imports
 * far more than any one alias uses, and an unused import fails `noUnusedLocals`.
 */
/**
 * Non-generic type aliases, carried over verbatim.
 *
 * ScriptType only replaces *generic* aliases — those are the ones conditional types and
 * `infer` live in. A plain `type Foo = 'a' | 'b'` has nothing to gain, but omitting it
 * would make the converted module export less than the original, so it is passed through
 * unchanged; the compiler already emits a hand-written alias as written.
 */
function plainAliases(file: string, text: string): string[] {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const out: string[] = []
  for (const stmt of sf.statements) {
    if (!ts.isTypeAliasDeclaration(stmt) || stmt.typeParameters?.length) continue
    const exported = ts.getCombinedModifierFlags(stmt) & ts.ModifierFlags.Export ? 'export ' : ''
    // The companion `declare const` matters: ScriptType code refers to a type by naming
    // it in expression position, and a bare `type X` alone is TS2693 there. It is
    // exported alongside the type, or an importing module gets the type only and hits
    // the same error one file over.
    out.push(
      `${exported}declare const ${stmt.name.text}: any\n` +
        `${exported}type ${stmt.name.text} = ${stmt.type.getText(sf)}`,
    )
  }
  return out
}

/**
 * How the original file's imports are reproduced for ScriptType source.
 *
 * A ScriptType type function is *called*, so an imported name has to exist in value
 * space. That is only true if the module it comes from was also converted, so imports
 * split two ways:
 *
 *   converted sibling  -> a value import redirected to `./x.st.js`
 *   anything else      -> an ambient shim, since a `.d.ts` exports no value and a value
 *                         import of one is TS2846
 *
 * A shim is honest about what it is: a declaration so the name resolves, carrying no
 * meaning. It is the same device the generated corpus uses, and the alternative — an
 * import that cannot typecheck — helps nobody.
 */
function carriedImports(
  originalText: string,
  code: string,
  file: string,
  converted: Set<string>,
  /** Names each converted module exports in *type* space, keyed by extensionless path. */
  typeExports: Map<string, Set<string>>,
  /** Filled with imported names that already have a type, so no shim is added for them. */
  alreadyTyped: Set<string>,
): string {
  const sf = ts.createSourceFile(file, originalText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const mentions = (n: string) => new RegExp(`(?<![A-Za-z0-9_$])${n}(?![A-Za-z0-9_$])`).test(code)
  const imports: string[] = []
  const shims: string[] = []

  const convertedBases = new Set(
    [...converted].map((f) => f.replace(/(\.d)?\.ts$/, '')),
  )

  for (const stmt of sf.statements) {
    if (!ts.isImportDeclaration(stmt) || !ts.isStringLiteral(stmt.moduleSpecifier)) continue
    const clause = stmt.importClause
    if (!clause?.namedBindings || !ts.isNamedImports(clause.namedBindings)) continue

    const names = clause.namedBindings.elements
      .map((el) => ({ from: (el.propertyName ?? el.name).text, as: el.name.text }))
      .filter((n) => mentions(n.as))
    if (!names.length) continue

    // `./words.d.ts` and `./words.js` both denote the same module on disk.
    const base = stmt.moduleSpecifier.text.replace(/\.(d\.ts|ts|js)$/, '')
    const resolved = path.resolve(path.dirname(file), base)
    if (convertedBases.has(resolved)) {
      const clauses = names.map((n) => (n.from === n.as ? n.as : `${n.from} as ${n.as}`))
      imports.push(`import { ${clauses.join(', ')} } from '${base}.st.js'`)
      // A name the target module exports as a type arrives with one, so shimming it
      // locally would be TS2440, "import conflicts with local declaration".
      const theirTypes = typeExports.get(resolved)
      for (const n of names) if (theirTypes?.has(n.from)) alreadyTyped.add(n.as)
    } else {
      for (const n of names) shims.push(n.as)
    }
  }

  const parts: string[] = []
  if (imports.length) parts.push(...imports)
  if (shims.length) {
    parts.push(
      '// Imported from modules that were not converted, so they export a type but no',
      '// value. Declared here so the names resolve; they carry no meaning. Converting',
      '// those modules too replaces these with real imports.',
      ...[...new Set(shims)].sort().flatMap((n) => [
        `declare const ${n}: any`,
        `type ${n}<A = any, B = any, C = any, D = any, E = any, F = any, G = any, H = any> = any`,
      ]),
    )
  }
  return parts.join('\n') + (parts.length ? '\n' : '')
}

function cmdWatch(args: Args): number {
  const inputs = args.positionals.length ? args.positionals : ['.']
  const run = () => {
    process.stdout.write(dim(`\n${new Date().toLocaleTimeString()} — rebuilding\n`))
    try {
      cmdBuild({ ...args, flags: { ...args.flags, quiet: false } }, { emit: true })
    } catch (e) {
      process.stderr.write(`${red('error')}: ${(e as Error).message}\n`)
    }
  }
  run()

  const dirs = new Set(
    collect(inputs).map((f) => path.dirname(f)),
  )
  for (const i of inputs) {
    const p = path.resolve(i)
    if (fs.existsSync(p) && fs.statSync(p).isDirectory()) dirs.add(p)
  }
  process.stdout.write(
    cyan(`\nwatching ${dirs.size} director${dirs.size === 1 ? 'y' : 'ies'} — ctrl-c to stop\n`),
  )

  let timer: NodeJS.Timeout | undefined
  for (const d of dirs) {
    fs.watch(d, { recursive: true }, (_e, name) => {
      if (!name || !ST_EXT.test(name)) return
      // Editors write in several steps; coalesce the burst into one rebuild.
      clearTimeout(timer)
      timer = setTimeout(run, 50)
    })
  }
  return -1 // keep the process alive
}

function cmdExplain(args: Args): number {
  const code = args.positionals[0]
  if (!code) {
    process.stdout.write(`${bold('Diagnostic codes')}\n\n`)
    for (const c of allCodes()) {
      const spec = explain(c, false)!.split('\n')
      process.stdout.write(`  ${cyan(c)}  ${spec[2]?.split('\n')[0]?.slice(0, 62) ?? ''}\n`)
    }
    process.stdout.write(dim(`\nscripttype explain <code>  for the full text\n`))
    return 0
  }
  const text = explain(code, COLOR)
  if (!text) {
    const near = didYouMean(code.toUpperCase(), allCodes())
    process.stderr.write(
      `${red('error')}: unknown diagnostic code '${code}'` +
        (near ? `\n${green('help')}: did you mean ${near}?` : '') +
        '\n',
    )
    return 1
  }
  process.stdout.write(text + '\n')
  return 0
}

function cmdBuiltins(args: Args): number {
  const filter = args.positionals[0]?.toLowerCase()
  const names = Object.keys(BUILTINS).sort()
  const shown = filter ? names.filter((n) => n.toLowerCase().includes(filter)) : names
  if (!shown.length) {
    process.stderr.write(`${red('error')}: no builtin matches '${filter}'\n`)
    return 1
  }
  const width = Math.max(...shown.map((n) => n.length))
  for (const n of shown) {
    process.stdout.write(`  ${cyan(n.padEnd(width))}  ${dim(BUILTINS[n]!.doc)}\n`)
  }
  process.stdout.write(dim(`\n${shown.length} of ${names.length} builtins\n`))
  return 0
}

const TSCONFIG = `{
  "compilerOptions": {
    // ScriptType requires a DOM-free lib: the DOM declares globals named \`length\`,
    // \`name\`, \`origin\`, \`status\`, \`top\` and others that collide with builtins.
    "lib": ["ES2022"],
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "strict": true,
    // A ScriptType parameter denotes a type, so there is no value-level type to infer
    // and "implicit any" carries no information. Everything else in strict stays on.
    "noImplicitAny": false,
    "noEmit": true
  },
  "include": ["**/*.st.ts", "scripttype.d.ts"]
}
`

const EXAMPLE = `/**
 * Split a string on a separator — the "hello world" of type-level programming.
 *
 * Build it with:   scripttype build example.st.ts
 * Check it with:   scripttype check example.st.ts
 */
export function Split(input: string, sep: string) {
  const out: string[] = []
  let rest = input
  while (includes(rest, sep)) {
    const [head, tail] = splitOnce(rest, sep)
    out.push(head)
    rest = tail
  }
  out.push(rest)
  return out
}
`

function cmdInit(args: Args): number {
  const dir = path.resolve(args.positionals[0] ?? '.')
  fs.mkdirSync(dir, { recursive: true })

  // `scripttype.d.ts` is a declaration file, so tsc does not emit it into `dist/`;
  // running from a build has to reach back into `src/`. Same list as AMBIENT_DTS.
  const dtsSource = [
    path.resolve(import.meta.dirname, 'scripttype.d.ts'),
    path.resolve(import.meta.dirname, '../src/scripttype.d.ts'),
  ].find((p) => fs.existsSync(p))
  if (!dtsSource) throw new UserError('scripttype.d.ts not found beside the compiler')
  const files: [string, string][] = [
    ['scripttype.d.ts', fs.readFileSync(dtsSource, 'utf8')],
    ['tsconfig.json', TSCONFIG],
    ['example.st.ts', EXAMPLE],
  ]

  let wrote = 0
  for (const [name, content] of files) {
    const dest = path.join(dir, name)
    if (fs.existsSync(dest) && !args.flags.force) {
      process.stdout.write(`${yellow('skip')} ${display(dest)} ${dim('(exists)')}\n`)
      continue
    }
    fs.writeFileSync(dest, content)
    process.stdout.write(`${green('✓')} ${display(dest)}\n`)
    wrote++
  }
  if (wrote) {
    process.stdout.write(
      `\n${bold('Next:')}\n` +
        `  scripttype build ${display(path.join(dir, 'example.st.ts'))}\n` +
        `  scripttype builtins          ${dim('# the builtin surface')}\n` +
        `  scripttype explain ST1102    ${dim('# any error code')}\n`,
    )
  }
  return 0
}

// A function, not a const: colour is only decided once flags are parsed, and a

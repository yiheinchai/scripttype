// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

export function main(argv: string[]): number {
  const args = parseArgs(argv)
  COLOR = args.flags['no-color'] ? false : colorsEnabled(process.stdout)

  if (args.flags.version) {
    process.stdout.write(`${VERSION}\n`)
    return 0
  }
  if (args.flags.help || !args.command || args.command === 'help') {
    process.stdout.write(HELP())
    return args.command || args.flags.help ? 0 : 1
  }

  switch (args.command) {
    case 'build':
      return cmdBuild(args, { emit: true })
    case 'check':
      return cmdBuild(args, { emit: false })
    case 'convert':
      return cmdConvert(args)
    case 'watch':
      return cmdWatch(args)
    case 'explain':
      return cmdExplain(args)
    case 'builtins':
      return cmdBuiltins(args)
    case 'init':
      return cmdInit(args)
    default: {
      const near = didYouMean(args.command, [
        'build', 'check', 'watch', 'convert', 'explain', 'builtins', 'init', 'help',
      ])
      process.stderr.write(
        `${red('error')}: unknown command '${args.command}'` +
          (near ? `\n${green('help')}: did you mean \`scripttype ${near}\`?` : '') +
          `\n\nRun \`scripttype --help\` for usage.\n`,
      )
      return 1
    }
  }
}

export function run(argv: string[]): void {
  let status: number
  try {
    status = main(argv)
  } catch (e) {
    if (e instanceof UserError) {
      process.stderr.write(`${red('error')}: ${e.message}\n`)
      process.exit(1)
    }
    // An unexpected throw is a compiler bug, and should read as one rather than as
    // something the user did wrong.
    process.stderr.write(
      `${red('internal error')}: the ScriptType compiler crashed. This is a bug.\n` +
        `${(e as Error).stack ?? String(e)}\n`,
    )
    process.exit(2)
  }
  if (status >= 0) process.exit(status)
}

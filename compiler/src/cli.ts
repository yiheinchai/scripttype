function cmdBuild(args: Args, { emit }: { emit: boolean }): number {
  const files = collect(args.positionals.length ? args.positionals : ['.'])
  if (!files.length) throw new UserError('no ScriptType files found (looking for *.st.ts)')

  const outDir = typeof args.flags.out === 'string' ? args.flags.out : undefined
  const toStdout = !!args.flags.stdout
  const force = !!args.flags.force
  const json = !!args.flags.json
  const started = Date.now()
  jsonDiagnostics.length = 0

  let errors = 0
  let warnings = 0
  let written = 0

  for (const file of files) {
    const r = processFile(file, { checkSource: !args.flags['no-check-source'] })
    const counts = report(r, json)
    errors += counts.errors
    warnings += counts.warnings
    if (!r.code || counts.errors) continue

    const body = BANNER(path.basename(file)) + '\n\n' + r.code
    if (toStdout) {
      process.stdout.write(body)
      continue
    }
    if (!emit || json) continue

    const dest = outputPath(file, outDir)
    // Never clobber a hand-written file that happens to sit at the output path.
    if (fs.existsSync(dest) && !force) {
      const existing = fs.readFileSync(dest, 'utf8')
      if (!existing.startsWith('// Generated by ScriptType')) {
        process.stderr.write(
          `${red('error')}: refusing to overwrite ${display(dest)} — it was not generated by ScriptType.\n` +
            `${green('help')}: pass --force, or --out <dir> to write elsewhere.\n\n`,
        )
        errors++
        continue
      }
      if (existing === body) continue // unchanged; leave mtime alone for watchers
    }
    fs.mkdirSync(path.dirname(dest), { recursive: true })
    fs.writeFileSync(dest, body)
    written++
    if (!args.flags.quiet) {
      process.stdout.write(`${green('✓')} ${display(file)} ${dim('→')} ${display(dest)}\n`)
    }
  }

  const ms = Date.now() - started
  if (json) {
    process.stdout.write(
      JSON.stringify(
        { files: files.length, errors, warnings, durationMs: ms, diagnostics: jsonDiagnostics },
        null,
        2,
      ) + '\n',
    )
    return errors ? 1 : 0
  }

  const parts = [dim(`${files.length} file${files.length === 1 ? '' : 's'}`)]
  if (emit && !toStdout) parts.push(dim(`${written} written`))
  if (warnings) parts.push(yellow(`${warnings} warning${warnings === 1 ? '' : 's'}`))
  parts.push(errors ? red(`${errors} error${errors === 1 ? '' : 's'}`) : green('0 errors'))
  if (!toStdout && !args.flags.quiet) {
    process.stdout.write(`\n${parts.join(dim(' · '))} ${dim(`(${ms}ms)`)}\n`)
  }
  return errors ? 1 : 0
}

function cmdWatch(args: Args): number {
  const inputs = args.positionals.length ? args.positionals : ['.']
  const run = () => {
    process.stdout.write(dim(`\n${new Date().toLocaleTimeString()} — rebuilding\n`))
    try {
      cmdBuild({ ...args, flags: { ...args.flags, quiet: false } }, { emit: true })
    } catch (e) {
      process.stderr.write(`${red('error')}: ${(e as Error).message}\n`)
    }
  }
  run()

  const dirs = new Set(
    collect(inputs).map((f) => path.dirname(f)),
  )
  for (const i of inputs) {
    const p = path.resolve(i)
    if (fs.existsSync(p) && fs.statSync(p).isDirectory()) dirs.add(p)
  }
  process.stdout.write(
    cyan(`\nwatching ${dirs.size} director${dirs.size === 1 ? 'y' : 'ies'} — ctrl-c to stop\n`),
  )

  let timer: NodeJS.Timeout | undefined
  for (const d of dirs) {
    fs.watch(d, { recursive: true }, (_e, name) => {
      if (!name || !ST_EXT.test(name)) return
      // Editors write in several steps; coalesce the burst into one rebuild.
      clearTimeout(timer)
      timer = setTimeout(run, 50)
    })
  }
  return -1 // keep the process alive
}

function cmdExplain(args: Args): number {
  const code = args.positionals[0]
  if (!code) {
    process.stdout.write(`${bold('Diagnostic codes')}\n\n`)
    for (const c of allCodes()) {
      const spec = explain(c, false)!.split('\n')
      process.stdout.write(`  ${cyan(c)}  ${spec[2]?.split('\n')[0]?.slice(0, 62) ?? ''}\n`)
    }
    process.stdout.write(dim(`\nscripttype explain <code>  for the full text\n`))
    return 0
  }
  const text = explain(code, COLOR)
  if (!text) {
    const near = didYouMean(code.toUpperCase(), allCodes())
    process.stderr.write(
      `${red('error')}: unknown diagnostic code '${code}'` +
        (near ? `\n${green('help')}: did you mean ${near}?` : '') +
        '\n',
    )
    return 1
  }
  process.stdout.write(text + '\n')
  return 0
}

function cmdBuiltins(args: Args): number {
  const filter = args.positionals[0]?.toLowerCase()
  const names = Object.keys(BUILTINS).sort()
  const shown = filter ? names.filter((n) => n.toLowerCase().includes(filter)) : names
  if (!shown.length) {
    process.stderr.write(`${red('error')}: no builtin matches '${filter}'\n`)
    return 1
  }
  const width = Math.max(...shown.map((n) => n.length))
  for (const n of shown) {
    process.stdout.write(`  ${cyan(n.padEnd(width))}  ${dim(BUILTINS[n]!.doc)}\n`)
  }
  process.stdout.write(dim(`\n${shown.length} of ${names.length} builtins\n`))
  return 0
}

const TSCONFIG = `{
  "compilerOptions": {
    // ScriptType requires a DOM-free lib: the DOM declares globals named \`length\`,
    // \`name\`, \`origin\`, \`status\`, \`top\` and others that collide with builtins.
    "lib": ["ES2022"],
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "strict": true,
    // A ScriptType parameter denotes a type, so there is no value-level type to infer
    // and "implicit any" carries no information. Everything else in strict stays on.
    "noImplicitAny": false,
    "noEmit": true
  },
  "include": ["**/*.st.ts", "scripttype.d.ts"]
}
`

const EXAMPLE = `/**
 * Split a string on a separator — the "hello world" of type-level programming.
 *
 * Build it with:   scripttype build example.st.ts
 * Check it with:   scripttype check example.st.ts
 */
export function Split(input: string, sep: string) {
  const out: string[] = []
  let rest = input
  while (includes(rest, sep)) {
    const [head, tail] = splitOnce(rest, sep)
    out.push(head)
    rest = tail
  }
  out.push(rest)
  return out
}
`

function cmdInit(args: Args): number {
  const dir = path.resolve(args.positionals[0] ?? '.')
  fs.mkdirSync(dir, { recursive: true })

  const dtsSource = path.resolve(import.meta.dirname, 'scripttype.d.ts')
  const files: [string, string][] = [
    ['scripttype.d.ts', fs.readFileSync(dtsSource, 'utf8')],
    ['tsconfig.json', TSCONFIG],
    ['example.st.ts', EXAMPLE],
  ]

  let wrote = 0
  for (const [name, content] of files) {
    const dest = path.join(dir, name)
    if (fs.existsSync(dest) && !args.flags.force) {
      process.stdout.write(`${yellow('skip')} ${display(dest)} ${dim('(exists)')}\n`)
      continue
    }
    fs.writeFileSync(dest, content)
    process.stdout.write(`${green('✓')} ${display(dest)}\n`)
    wrote++
  }
  if (wrote) {
    process.stdout.write(
      `\n${bold('Next:')}\n` +
        `  scripttype build ${display(path.join(dir, 'example.st.ts'))}\n` +
        `  scripttype builtins          ${dim('# the builtin surface')}\n` +
        `  scripttype explain ST1102    ${dim('# any error code')}\n`,
    )
  }
  return 0
}

// A function, not a const: colour is only decided once flags are parsed, and a
// module-level template literal would bake in the default.

/**
 * The `scripttype` command line.
 *
 * This is the whole product surface for someone who is not working on the compiler:
 * point it at a `.st.ts` file and get TypeScript out, with errors that say what to fix.
 * Everything else in `src/` is either the compiler or a verification harness.
 */
import fs from 'node:fs'
import path from 'node:path'
import { compile, CompileError } from './compile.js'
import { typecheckScriptType } from './typecheck.js'
import { freeNames } from './freenames.js'
import { BUILTINS } from './builtins.js'
import {
  type Diagnostic,
  allCodes,
  colorsEnabled,
  diagnosticFromNode,
  didYouMean,
  explain,
  formatDiagnostic,
} from './diagnostics.js'

const VERSION = '0.1.0'

const BANNER = (from: string) =>
  `// Generated by ScriptType from ${from}. Do not edit — edit the .st.ts and rebuild.`

// ---------------------------------------------------------------------------
// Argument parsing
// ---------------------------------------------------------------------------

interface Args {
  command: string
  positionals: string[]
  flags: Record<string, string | boolean>
}

function parseArgs(argv: string[]): Args {
  const flags: Record<string, string | boolean> = {}
  const positionals: string[] = []
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]!
    if (a === '--') {
      positionals.push(...argv.slice(i + 1))
      break
    }
    if (a.startsWith('--')) {
      const eq = a.indexOf('=')
      if (eq !== -1) {
        flags[a.slice(2, eq)] = a.slice(eq + 1)
      } else {
        const name = a.slice(2)
        // Only flags that take a value consume the next argument.
        const next = argv[i + 1]
        if (VALUE_FLAGS.has(name) && next !== undefined && !next.startsWith('-')) {
          flags[name] = next
          i++
        } else {
          flags[name] = true
        }
      }
    } else if (a.startsWith('-') && a.length > 1) {
      for (const ch of a.slice(1)) flags[SHORT[ch] ?? ch] = true
    } else {
      positionals.push(a)
    }
  }
  const command = positionals.shift() ?? ''
  return { command, positionals, flags }
}

const VALUE_FLAGS = new Set(['out', 'ext'])
const SHORT: Record<string, string> = { h: 'help', v: 'version', w: 'watch', o: 'out' }

// ---------------------------------------------------------------------------
// Output plumbing
// ---------------------------------------------------------------------------

let COLOR = true

function paint(code: string, s: string): string {
  return COLOR ? `${code}${s}\x1b[0m` : s
}
const bold = (s: string) => paint('\x1b[1m', s)
const dim = (s: string) => paint('\x1b[2m', s)
const red = (s: string) => paint('\x1b[31m', s)
const green = (s: string) => paint('\x1b[32m', s)
const yellow = (s: string) => paint('\x1b[33m', s)
const cyan = (s: string) => paint('\x1b[36m', s)

/** Path shown to the user: relative to cwd when that is shorter. */
function display(p: string): string {
  const rel = path.relative(process.cwd(), p)
  return rel && !rel.startsWith('..') && rel.length < p.length ? rel : p
}

// ---------------------------------------------------------------------------
// File discovery
// ---------------------------------------------------------------------------

const ST_EXT = /\.st\.(ts|js)$/

function collect(inputs: string[]): string[] {
  const out: string[] = []
  const walk = (p: string) => {
    let st: fs.Stats
    try {
      st = fs.statSync(p)
    } catch {
      throw new UserError(`no such file or directory: ${display(p)}`)
    }
    if (st.isDirectory()) {
      for (const e of fs.readdirSync(p, { withFileTypes: true })) {
        if (e.name === 'node_modules' || e.name.startsWith('.')) continue
        walk(path.join(p, e.name))
      }
    } else if (ST_EXT.test(p)) {
      out.push(path.resolve(p))
    }
  }
  for (const i of inputs) {
    const resolved = path.resolve(i)
    // An explicitly named file is compiled whatever its extension; only directory
    // walks filter by `.st.ts`, so `scripttype build one-off.ts` still works.
    if (fs.existsSync(resolved) && fs.statSync(resolved).isFile()) out.push(resolved)
    else walk(resolved)
  }
  return [...new Set(out)]
}

/** Where a source file's TypeScript goes: `foo.st.ts` -> `foo.ts`. */
function outputPath(src: string, outDir: string | undefined): string {
  const base = path.basename(src).replace(ST_EXT, '.ts').replace(/\.ts$/, '.ts')
  const name = ST_EXT.test(src) ? base : path.basename(src).replace(/\.[^.]+$/, '') + '.types.ts'
  return path.join(outDir ?? path.dirname(src), name)
}

class UserError extends Error {}

/**
 * ScriptType-specific advice for the TypeScript errors a `.st.ts` actually hits.
 *
 * These fire while checking the *source*, where names mean something different from
 * ordinary TypeScript — so tsc's own wording, while accurate, points the wrong way.
 */
const TS_HINTS: Record<number, string> = {
  2307:
    'A ScriptType module `x.st.ts` is imported as `./x.st.js` — that is the specifier ' +
    'TypeScript resolves, and the compiler rewrites it to `./x.js` in the output.',
  1361:
    'Import it as a value, not `import type`: a ScriptType type function is *called*, ' +
    'so the source needs a value binding. The emitted import is type-only either way.',
  2304:
    'Declare it, import it, or check `scripttype builtins` — a ScriptType file has no ' +
    'ambient globals beyond the builtin surface.',
  2693:
    'This resolved to a compiled type rather than to ScriptType source. Import the ' +
    'source instead: `./x.st.js`, not `./x.js`.',
  2451:
    'A builtin already has this name. The DOM lib also collides with several; make sure ' +
    'your tsconfig sets "lib" to something without DOM, e.g. ["ES2022"].',
}

// ---------------------------------------------------------------------------
// The per-file pipeline
// ---------------------------------------------------------------------------

interface FileResult {
  file: string
  text: string
  code?: string
  diagnostics: Diagnostic[]
}

/**
 * Compile one file and collect every diagnostic it produces.
 *
 * Three checks run, in the order a user cares about them:
 *   1. the source typechecks as TypeScript against the builtin surface (`--strict-source`),
 *   2. it lowers to type-level TypeScript,
 *   3. the names it references actually exist (a typo'd builtin is otherwise silently
 *      emitted as a reference to a type nobody declared).
 */
function processFile(file: string, opts: { checkSource: boolean }): FileResult {
  const text = fs.readFileSync(file, 'utf8')
  const diagnostics: Diagnostic[] = []

  if (opts.checkSource) {
    // Key by absolute path, not basename: the typecheck host falls back to the real
    // filesystem for anything it does not hold, so a relative import between two
    // ScriptType modules only resolves if the importer has its true location.
    const tc = typecheckScriptType({ [file]: text }, freeNames(text).values)
    for (const d of tc.diagnostics) {
      diagnostics.push({
        // Surfaced under TypeScript's own code, not a ScriptType one: this is tsc
        // speaking about the source, and TS2307 is what the user can search for.
        code: `TS${d.tsCode}`,
        message: d.message,
        file,
        start: d.start,
        length: d.length,
        severity: 'warning',
        help: TS_HINTS[d.tsCode],
      })
    }
    // Diagnostics with no span (a missing source file, say) still have to surface.
    if (tc.diagnostics.length < tc.errors.length) {
      for (const e of tc.errors.slice(tc.diagnostics.length)) {
        diagnostics.push({ code: 'ST0001', message: e, file, severity: 'warning' })
      }
    }
  }

  let code: string | undefined
  try {
    code = compile(text, { fileName: file }).code
  } catch (e) {
    if (e instanceof CompileError) {
      diagnostics.push(diagnosticFromNode(e.code, e.message, e.node, e.help))
      return { file, text, diagnostics }
    }
    throw e
  }

  for (const d of unresolvedNames(text, file)) diagnostics.push(d)
  return { file, text, code, diagnostics }
}

/**
 * Names used in call position that are neither declared in the file, imported, nor
 * builtins. These compile silently into references to a nonexistent type, which is the
 * worst failure mode the language has: a typo that surfaces much later, somewhere else.
 */
function unresolvedNames(text: string, file: string): Diagnostic[] {
  const { values } = freeNames(text)
  const out: Diagnostic[] = []
  for (const name of values) {
    if (BUILTINS[name]) continue
    // A capitalised free name is almost always a type imported from elsewhere, which is
    // legitimate; a lowercase one matching no builtin is almost always a typo.
    if (name[0] === name[0]?.toUpperCase()) continue
    const near = didYouMean(name, Object.keys(BUILTINS))
    if (!near) continue
    const at = text.indexOf(name)
    out.push({
      code: 'ST0002',
      message: `'${name}' is not a ScriptType builtin and is not declared in this file`,
      help: `Did you mean \`${near}\`? Run \`scripttype builtins\` to see them all.`,
      file,
      start: at >= 0 ? at : undefined,
      length: name.length,
      severity: 'warning',
    })
  }
  return out
}

/** Collected for `--json`, so editors and CI can consume diagnostics directly. */
interface JsonDiagnostic {
  file: string
  line: number
  column: number
  endLine: number
  endColumn: number
  severity: 'error' | 'warning'
  code: string
  message: string
  help?: string
}

const jsonDiagnostics: JsonDiagnostic[] = []

function report(r: FileResult, json: boolean): { errors: number; warnings: number } {
  let errors = 0
  let warnings = 0
  for (const d of r.diagnostics) {
    const severity = d.severity ?? 'error'
    if (severity === 'warning') warnings++
    else errors++

    if (json) {
      const start = positionOf(r.text, d.start ?? 0)
      const end = positionOf(r.text, (d.start ?? 0) + (d.length ?? 0))
      jsonDiagnostics.push({
        file: display(d.file ?? r.file),
        line: start.line,
        column: start.column,
        endLine: end.line,
        endColumn: end.column,
        severity,
        code: d.code,
        message: d.message,
        help: d.help,
      })
      continue
    }

    process.stderr.write(
      formatDiagnostic({ ...d, file: display(d.file ?? r.file) }, {
        text: r.text,
        color: COLOR,
        context: 1,
      }) + '\n\n',
    )
  }
  return { errors, warnings }
}

/** 1-based line and column of an absolute offset. */
function positionOf(text: string, offset: number): { line: number; column: number } {
  let line = 1
  let lineStart = 0
  for (let i = 0; i < offset && i < text.length; i++) {
    if (text[i] === '\n') {
      line++
      lineStart = i + 1
    }
  }
  return { line, column: offset - lineStart + 1 }
}


#!/usr/bin/env tsx
/**
 * Materialise the ScriptType sources for the corpus.
 *
 * The round-trip harness verifies in memory; this writes the actual `.stype` files to
 * disk, mirroring the corpus tree, so every type-level alias in the corpus has a
 * visible, readable ScriptType counterpart next to its verification status.
 *
 * Statuses come from a previous `inplace.ts --json` run, so this pass only needs to
 * decompile (cheap) rather than re-typecheck.
 *
 * Usage:
 *   tsx src/materialize.ts <statuses-dir> [--out ../scripttype] [--root <corpus-rel>]
 */
import fs from 'node:fs'
import path from 'node:path'
import { decompileFile } from './decompile.js'
import { compile } from './compile.js'
import { declarePreamble } from './freenames.js'
import { REPO_ROOT } from './corpus.js'
import type { Status } from './batch.js'

interface Outcome {
  file: string
  name: string
  status: Status
  gaps: string[]
  detail?: string
}

const args = process.argv.slice(2)
const statusDir = args.find((a) => !a.startsWith('--'))
if (!statusDir) {
  console.error('usage: materialize.ts <statuses-dir> [--out DIR] [--root corpus-rel]')
  process.exit(2)
}
const outIdx = args.indexOf('--out')
const outRoot = path.resolve(outIdx >= 0 ? args[outIdx + 1]! : path.join(REPO_ROOT, 'scripttype'))
const rootIdx = args.indexOf('--root')
const onlyRoot = rootIdx >= 0 ? args[rootIdx + 1] : undefined

// file -> name -> outcome
const statuses = new Map<string, Map<string, Outcome>>()
if (fs.existsSync(statusDir)) {
  for (const f of fs.readdirSync(statusDir)) {
    if (!f.endsWith('.json')) continue
    let list: Outcome[]
    try {
      list = JSON.parse(fs.readFileSync(path.join(statusDir, f), 'utf8'))
    } catch {
      continue
    }
    for (const o of list) {
      if (!statuses.has(o.file)) statuses.set(o.file, new Map())
      statuses.get(o.file)!.set(o.name, o)
    }
  }
}

const MARK: Record<Status, string> = {
  covered: 'verified type-identical to the original',
  raw: 'uses raw() — language gap, does not count as covered',
  'compile-error': 'does not compile yet',
  mismatch: 'compiles but is not type-identical yet',
  'unresolved-deps': 'could not be judged in isolation',
  'reference-error': 'reference could not be resolved',
  'typecheck-error': 'the ScriptType does not itself typecheck as TypeScript',
}

let files = 0
let written = 0
const perStatus = new Map<Status, number>()

const targetFiles = onlyRoot
  ? [...statuses.keys()].filter((f) => f.startsWith(onlyRoot))
  : [...statuses.keys()]

for (const rel of targetFiles.sort()) {
  const abs = path.join(REPO_ROOT, rel)
  if (!fs.existsSync(abs)) continue
  let text: string
  try {
    text = fs.readFileSync(abs, 'utf8')
  } catch {
    continue
  }
  let entries
  try {
    entries = decompileFile(abs, text)
  } catch {
    continue
  }
  if (!entries.length) continue
  files++

  const byName = statuses.get(rel) ?? new Map<string, Outcome>()
  const blocks: string[] = []
  const counts = new Map<Status, number>()

  for (const e of entries) {
    const o = byName.get(e.name)
    const status: Status = o?.status ?? 'unresolved-deps'
    counts.set(status, (counts.get(status) ?? 0) + 1)
    perStatus.set(status, (perStatus.get(status) ?? 0) + 1)

    const tag = status === 'covered' ? '✓' : '✗'
    const note = [`// ${tag} ${e.name}: ${MARK[status]}`]
    if (status === 'raw' && e.result.gaps.length) {
      note.push(`//   gap: ${[...new Set(e.result.gaps)].join('; ')}`)
    } else if (o?.detail && status !== 'covered') {
      note.push(`//   ${o.detail.slice(0, 160)}`)
    }

    // Show the TypeScript this compiles to, so the two forms sit side by side.
    let emitted = ''
    if (status !== 'raw') {
      try {
        emitted = compile(e.result.source, { fileName: `${e.name}.st.ts`, includePrelude: false })
          .code.trimEnd()
      } catch {
        emitted = ''
      }
    }

    blocks.push(
      [
        ...note,
        e.result.source.trimEnd(),
        emitted ? '/* compiles to:\n' + emitted.split('\n').map((l) => ' * ' + l).join('\n') + '\n */' : '',
      ]
        .filter(Boolean)
        .join('\n'),
    )
  }

  const summary = [...counts]
    .sort((a, b) => b[1] - a[1])
    .map(([s, n]) => `${n} ${s}`)
    .join(', ')

  const header = [
    '/**',
    ` * ScriptType for ${rel}`,
    ' *',
    ` * Generated by the ScriptType decompiler from the corpus source above, then verified`,
    ` * by recompiling and comparing to the original with the TypeScript checker.`,
    ` * ${entries.length} type-level aliases: ${summary}`,
    ' *',
    ' * Do not edit: regenerate with `tsx src/materialize.ts`.',
    ' */',
    '',
  ].join('\n')

  const body = blocks.join('\n\n') + '\n'
  // Declare the names this file references but does not define, so it typechecks
  // standalone. Both a value and a type: ScriptType applies types in call position.
  const preamble = declarePreamble(body)

  const dest = path.join(outRoot, rel.replace(/\.tsx?$/, '.st.ts'))
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, header + preamble + body)
  written++
}

const total = [...perStatus.values()].reduce((a, b) => a + b, 0)
const covered = perStatus.get('covered') ?? 0
const lines = [
  '# Generated ScriptType sources',
  '',
  `Mirrors the corpus tree: every \`<repo>/<path>.ts\` with type-level aliases has a`,
  `\`<repo>/<path>.st.ts\` here containing the ScriptType form of each alias, the TypeScript it`,
  `compiles back to, and its verification status.`,
  '',
  '## What these are, and what they are not',
  '',
  'These files are produced by the **decompiler**, which translates each conditional type into',
  'statement form: `if (matches<Pattern>(x)) { return … }` plus early returns, instead of a',
  'nested ternary. That is already a large readability gain — control flow becomes linear and',
  'each branch is named — and every file records whether it recompiles to a type-identical result.',
  '',
  'What the decompiler does **not** do is recover loops. A recursive type stays recursive here,',
  'rather than becoming the `while` loop a human would write. Loop recovery (recognising a',
  'tail-recursive accumulator and re-expressing it as iteration) is the inverse of the',
  'compiler\'s loop lowering and is not implemented.',
  '',
  'For hand-written ScriptType in the intended imperative style — loops, mutable accumulators,',
  '`push()` — see the `corpus/` directory, where each target is authored by hand and held to a',
  'stricter per-sample equivalence gate.',
  '',
  `- files: ${written}`,
  `- aliases: ${total}`,
  `- verified type-identical: ${covered} (${total ? ((covered / total) * 100).toFixed(1) : '0'}%)`,
  '',
  '| status | count | meaning |',
  '|---|--:|---|',
  ...[...perStatus]
    .sort((a, b) => b[1] - a[1])
    .map(([s, n]) => `| \`${s}\` | ${n} | ${MARK[s]} |`),
]
fs.mkdirSync(outRoot, { recursive: true })
fs.writeFileSync(path.join(outRoot, 'README.md'), lines.join('\n') + '\n')

console.log(`wrote ${written} .st.ts files under ${outRoot}`)
console.log(`aliases: ${total}, verified: ${covered}`)
for (const [s, n] of [...perStatus].sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(5)}  ${s}`)

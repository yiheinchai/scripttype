/**
 * End-to-end tests for the `scripttype` executable.
 *
 * These run the real binary as a subprocess rather than importing `main()`, because the
 * things most likely to break are the parts an import would skip: the tsx-registering
 * shim, argument parsing, writing files, and exit codes.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

const BIN = path.resolve(import.meta.dirname, '../bin/scripttype.mjs')

interface Run {
  status: number
  stdout: string
  stderr: string
}

function run(args: string[], cwd: string): Run {
  try {
    const stdout = execFileSync(BIN, args, {
      cwd,
      encoding: 'utf8',
      // Keep output deterministic: no colour, and stderr captured rather than inherited.
      env: { ...process.env, NO_COLOR: '1' },
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    return { status: 0, stdout, stderr: '' }
  } catch (e) {
    const err = e as { status?: number; stdout?: string; stderr?: string }
    return { status: err.status ?? 1, stdout: err.stdout ?? '', stderr: err.stderr ?? '' }
  }
}

let dir: string
beforeAll(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'scripttype-cli-'))
})
afterAll(() => {
  fs.rmSync(dir, { recursive: true, force: true })
})

const write = (name: string, text: string) => {
  const p = path.join(dir, name)
  fs.mkdirSync(path.dirname(p), { recursive: true })
  fs.writeFileSync(p, text)
  return p
}

describe('scripttype CLI', () => {
  it('prints help and exits 0', () => {
    const r = run(['--help'], dir)
    expect(r.status).toBe(0)
    expect(r.stdout).toContain('scripttype <command>')
  })

  it('exits 1 with no command, so a bare invocation is not mistaken for success', () => {
    expect(run([], dir).status).toBe(1)
  })

  it('suggests a near-miss command', () => {
    const r = run(['buld'], dir)
    expect(r.status).toBe(1)
    expect(r.stderr).toContain('did you mean `scripttype build`')
  })

  it('builds a file to a sibling .ts with a generated banner', () => {
    write('a.st.ts', 'export function Id(t: unknown) { return t }\n')
    const r = run(['build', 'a.st.ts'], dir)
    expect(r.status).toBe(0)
    const out = fs.readFileSync(path.join(dir, 'a.ts'), 'utf8')
    expect(out).toContain('// Generated by ScriptType from a.st.ts')
    expect(out).toContain('export type Id<T> = T')
  })

  it('refuses to overwrite a file it did not generate, unless forced', () => {
    write('b.st.ts', 'export function B(t: unknown) { return t }\n')
    write('b.ts', 'export const handWritten = 1\n')

    const refused = run(['build', 'b.st.ts'], dir)
    expect(refused.status).toBe(1)
    expect(refused.stderr).toContain('refusing to overwrite')
    expect(fs.readFileSync(path.join(dir, 'b.ts'), 'utf8')).toBe('export const handWritten = 1\n')

    const forced = run(['build', 'b.st.ts', '--force'], dir)
    expect(forced.status).toBe(0)
    expect(fs.readFileSync(path.join(dir, 'b.ts'), 'utf8')).toContain('export type B<T> = T')
  })

  it('redirects output with --out', () => {
    write('c.st.ts', 'export function C(t: unknown) { return t }\n')
    expect(run(['build', 'c.st.ts', '--out', 'gen'], dir).status).toBe(0)
    expect(fs.existsSync(path.join(dir, 'gen/c.ts'))).toBe(true)
  })

  it('writes nothing for `check`, and exits 1 on an error', () => {
    write('bad.st.ts', 'export function Bad(t: string) {\n  console.log(t)\n  return t\n}\n')
    const r = run(['check', 'bad.st.ts'], dir)
    expect(r.status).toBe(1)
    expect(r.stderr).toContain('error[ST1102]')
    expect(fs.existsSync(path.join(dir, 'bad.ts'))).toBe(false)
  })

  it('emits machine-readable diagnostics with --json', () => {
    const r = run(['check', 'bad.st.ts', '--json'], dir)
    expect(r.status).toBe(1)
    const parsed = JSON.parse(r.stdout)
    expect(parsed.errors).toBe(1)
    expect(parsed.diagnostics[0]).toMatchObject({
      code: 'ST1102',
      severity: 'error',
      line: 2,
      column: 3,
    })
  })

  it('walks a directory for .st.ts and ignores everything else', () => {
    const sub = path.join(dir, 'walk')
    fs.mkdirSync(sub, { recursive: true })
    fs.writeFileSync(path.join(sub, 'x.st.ts'), 'export function X(t: unknown) { return t }\n')
    fs.writeFileSync(path.join(sub, 'notes.md'), '# not source\n')
    fs.writeFileSync(path.join(sub, 'plain.ts'), 'export const y = 1\n')
    const r = run(['build', 'walk'], dir)
    expect(r.status).toBe(0)
    expect(r.stdout).toContain('1 file')
    expect(fs.existsSync(path.join(sub, 'x.ts'))).toBe(true)
  })

  it('scaffolds a project that typechecks under stock tsc', () => {
    const proj = path.join(dir, 'scaffold')
    expect(run(['init', proj], dir).status).toBe(0)
    for (const f of ['scripttype.d.ts', 'tsconfig.json', 'example.st.ts']) {
      expect(fs.existsSync(path.join(proj, f)), f).toBe(true)
    }
    const tsc = path.resolve(import.meta.dirname, '../node_modules/.bin/tsc')
    // The scaffold's own claim: a .st.ts is ordinary TypeScript, so it must check clean.
    expect(() => execFileSync(tsc, ['--noEmit'], { cwd: proj, stdio: 'pipe' })).not.toThrow()
  })

  it('explains a code and rejects an unknown one', () => {
    expect(run(['explain', 'ST1102'], dir).stdout).toContain('There is no global object')
    const bad = run(['explain', 'ST9999'], dir)
    expect(bad.status).toBe(1)
    expect(bad.stderr).toContain("unknown diagnostic code 'ST9999'")
  })

  it('lists and filters builtins', () => {
    const all = run(['builtins'], dir)
    expect(all.status).toBe(0)
    const filtered = run(['builtins', 'starts'], dir)
    expect(filtered.stdout).toContain('startsWith')
    expect(filtered.stdout.split('\n').length).toBeLessThan(all.stdout.split('\n').length)
  })

  it('converts existing TypeScript, and the result recompiles to the same types', () => {
    // The migration path is only worth having if what comes out is trustworthy, so this
    // asserts the whole loop: convert, build, then let tsc compare the two.
    const proj = path.join(dir, 'convert')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(
      path.join(proj, 'types.ts'),
      [
        'export type IsString<T> = T extends string ? true : false',
        'export type TrimLeft<S extends string> = S extends ` ${infer R}` ? TrimLeft<R> : S',
        'export type Keys<O> = { [K in keyof O]: K }[keyof O]',
      ].join('\n') + '\n',
    )

    expect(run(['convert', 'types.ts'], proj).status).toBe(0)
    const st = fs.readFileSync(path.join(proj, 'types.st.ts'), 'utf8')
    // Recursion became a loop and the guard became the JavaScript spelling.
    expect(st).toContain("typeof T === 'string'")
    expect(st).toContain('while (true)')

    expect(run(['build', 'types.st.ts', '--out', 'gen', '--no-check-source'], proj).status).toBe(0)
    fs.writeFileSync(
      path.join(proj, 'eq.ts'),
      [
        `import type * as O from './types.js'`,
        `import type * as C from './gen/types.js'`,
        'type Eq<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false',
        `const a: Eq<O.IsString<'x'>, C.IsString<'x'>> = true`,
        'const b: Eq<O.IsString<42>, C.IsString<42>> = true',
        `const c: Eq<O.TrimLeft<'   x'>, C.TrimLeft<'   x'>> = true`,
        'const d: Eq<O.Keys<{ a: 1; b: 2 }>, C.Keys<{ a: 1; b: 2 }>> = true',
      ].join('\n') + '\n',
    )
    const tsc = path.resolve(import.meta.dirname, '../node_modules/.bin/tsc')
    expect(() =>
      execFileSync(
        tsc,
        ['--noEmit', '--strict', '--lib', 'ES2022', '--target', 'ES2022',
         '--moduleResolution', 'bundler', '--module', 'esnext', 'eq.ts'],
        { cwd: proj, stdio: 'pipe' },
      ),
    ).not.toThrow()
  })

  it('flags what it could not express instead of quietly emitting raw()', () => {
    const proj = path.join(dir, 'convert-hard')
    fs.mkdirSync(proj, { recursive: true })
    // A `this` parameter is a position rather than a type, so it has nowhere to go in a
    // parameter tuple — unlike the call signature this test used to use, which the
    // language can now express.
    fs.writeFileSync(
      path.join(proj, 'hard.ts'),
      'export type Handler<T> = { run(this: T): void; name: string }\n',
    )
    const r = run(['convert', 'hard.ts'], proj)
    expect(r.stdout).toContain('need review')
    const out = fs.readFileSync(path.join(proj, 'hard.st.ts'), 'utf8')
    expect(out).toContain('TODO(scripttype)')
    expect(out).toContain('`this` parameter')
  })

  it('redirects an import between two converted modules, and shims one that is not', () => {
    const proj = path.join(dir, 'convert-imports')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(path.join(proj, 'words.ts'), 'export type Words<S extends string> = [S]\n')
    fs.writeFileSync(
      path.join(proj, 'use.ts'),
      [
        `import type { Words } from './words.js'`,
        `import type { Elsewhere } from './not-converted.js'`,
        'export type A<S extends string> = Words<S>',
        'export type B<S extends string> = Elsewhere<S>',
      ].join('\n') + '\n',
    )
    expect(run(['convert', '.'], proj).status).toBe(0)
    const out = fs.readFileSync(path.join(proj, 'use.st.ts'), 'utf8')
    // words.ts was converted, so the import points at its ScriptType and stays an import.
    expect(out).toContain(`import { Words } from './words.st.js'`)
    // not-converted.js was not, so it exports no value a ScriptType call could use.
    expect(out).not.toContain('not-converted')
    expect(out).toContain('declare const Elsewhere: any')
  })

  it('does not redirect to a module that produced no ScriptType', () => {
    // A file with nothing generic in it is not converted, so pointing at its `.st.js`
    // would dangle.
    const proj = path.join(dir, 'convert-nogeneric')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(path.join(proj, 'plain.ts'), 'export type Plain = 1 | 2\n')
    fs.writeFileSync(
      path.join(proj, 'use.ts'),
      `import type { Plain } from './plain.js'\nexport type A<T> = [T, Plain]\n`,
    )
    run(['convert', '.'], proj)
    expect(fs.existsSync(path.join(proj, 'plain.st.ts'))).toBe(false)
    expect(fs.readFileSync(path.join(proj, 'use.st.ts'), 'utf8')).not.toContain('plain.st.js')
  })

  it('carries non-generic aliases over so the module still exports them', () => {
    const proj = path.join(dir, 'convert-plain')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(
      path.join(proj, 'm.ts'),
      `export type Tag = 'a' | 'b'\nexport type Wrap<T> = [T, Tag]\n`,
    )
    run(['convert', 'm.ts'], proj)
    const out = fs.readFileSync(path.join(proj, 'm.st.ts'), 'utf8')
    expect(out).toContain(`export type Tag = 'a' | 'b'`)
    expect(out).toContain('export function Wrap')
  })

  it('says it skipped .d.ts rather than reporting nothing to do', () => {
    // type-fest and friends ship their type-level code as .d.ts, so "no TypeScript
    // files found" would be actively misleading there.
    const proj = path.join(dir, 'convert-dts')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(path.join(proj, 'x.d.ts'), 'export type F<T> = T\n')
    const skipped = run(['convert', '.'], proj)
    expect(skipped.status).toBe(1)
    expect(skipped.stderr).toContain('--declarations')

    expect(run(['convert', '.', '--declarations'], proj).status).toBe(0)
    // `x.d.ts` becomes `x.st.ts`, not `x.d.st.ts` — the result is source, not a
    // declaration file, and sibling imports are written `./x.st.js`.
    expect(fs.existsSync(path.join(proj, 'x.st.ts'))).toBe(true)
  })

  it('refuses to replace an existing .st.ts without --force', () => {
    const proj = path.join(dir, 'convert-clobber')
    fs.mkdirSync(proj, { recursive: true })
    fs.writeFileSync(path.join(proj, 'x.ts'), 'export type F<T> = T\n')
    fs.writeFileSync(path.join(proj, 'x.st.ts'), '// hand-written, do not lose me\n')
    run(['convert', 'x.ts'], proj)
    expect(fs.readFileSync(path.join(proj, 'x.st.ts'), 'utf8')).toContain('do not lose me')
    run(['convert', 'x.ts', '--force'], proj)
    expect(fs.readFileSync(path.join(proj, 'x.st.ts'), 'utf8')).toContain('export function F')
  })

  it('reports several errors in one run', () => {
    write(
      'many.st.ts',
      [
        'export function A(t: string) {',
        '  console.log(t)',
        '  return t',
        '}',
        'export function B(t: string) {',
        '  let x = 1',
        '  x += 2',
        '  return x',
        '}',
      ].join('\n'),
    )
    const r = run(['check', 'many.st.ts', '--json'], dir)
    expect(JSON.parse(r.stdout).diagnostics.map((d: { code: string }) => d.code)).toEqual([
      'ST1102',
      'ST1101',
    ])
  })
})

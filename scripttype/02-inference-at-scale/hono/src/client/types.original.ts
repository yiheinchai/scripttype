export type GlobalResponseDefinition = {
  [S in StatusCode]?: {
    [F in KnownResponseFormat]?: unknown
  }
}

export type ToEndpoints<Def extends GlobalResponseDefinition, R> = {
  [S in keyof Def & StatusCode]: {
    [F in keyof Def[S] & KnownResponseFormat]: Omit<R, 'output' | 'status' | 'outputFormat'> & {
      output: Def[S][F]
      status: S
      outputFormat: F
    }
  }[keyof Def[S] & KnownResponseFormat]
}[keyof Def & StatusCode]

export type ModRoute<R, Def extends GlobalResponseDefinition> = R extends Endpoint
  ? R | ToEndpoints<Def, R>
  : R

export type ModSchema<D, Def extends GlobalResponseDefinition> = {
  [K in keyof D]: {
    [M in keyof D[K]]: ModRoute<D[K][M], Def>
  }
}


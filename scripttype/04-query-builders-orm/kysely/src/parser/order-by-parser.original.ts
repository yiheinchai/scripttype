export type OrderByExpression<DB, TB extends keyof DB, O> =
  | StringReference<DB, TB>
  | (keyof O & string)
  | ExpressionOrFactory<DB, TB, any>
  | DynamicReferenceBuilder<any>

export type OrderByDirection = 'asc' | 'desc'

